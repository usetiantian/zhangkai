#!/usr/bin/env node
/**
 * anti-pattern-guard.cjs - PreToolUse guard for STRUCTURAL anti-patterns.
 *
 * WHAT THIS IS
 * ------------
 * A project-agnostic safety net for Claude Code sessions in any codebase
 * with build artifacts. Detects two well-known structural mistakes:
 *
 *   1. Manually editing files inside a build artifact directory
 *      (e.g. release/<plat>-unpacked/, app.asar.unpacked/, app.asar).
 *      These are GENERATED; manual edits get overwritten on the next build
 *      and leave asar/pak/icu metadata out of sync with actual contents.
 *
 *   2. Hardcoding PIDs in process kill commands (Stop-Process -Id <NNNNN>).
 *      PIDs change every launch; the right approach is to find the process
 *      by name (Get-Process / pgrep) and kill the matching PIDs.
 *
 * WHAT THIS IS NOT
 * ----------------
 * This hook is NOT aware of any specific build tool or project.
 * The detected PATTERNS are generic build-artifact /
 * process-kill shapes. The MESSAGE TEXT can be overridden per-project via
 * `.claude/hooks/anti-pattern-redirects.json` next to this file so the
 * same hook ships in any repo without modification.
 *
 * No deps. Pure stdlib.
 *
 * Exit codes per Claude Code hook contract:
 *   0  + empty stdout    = allow
 *   0  + JSON stdout     = apply the permissionDecision in the JSON
 *   2  + stderr          = block, model sees stderr as tool result
 */

const fs = require("fs");
const path = require("path");

// Generic build-artifact path fragments. Fire on any project whose
// build tool stages unpacked output into a per-platform subdirectory.
const FORBIDDEN_PATH_FRAGMENTS = [
  "/release/win-unpacked/",
  "/release/linux-unpacked/",
  "/release/mac/",
  "/release/mac-arm64/",
  "/resources/app.asar.unpacked/",
  "/resources/app.asar",
];

const PATTERNS = [
  {
    name: "manual-edit-of-build-artifact",
    matches: ({ toolName, filePath }) => {
      if (toolName !== "Edit" && toolName !== "Write" && toolName !== "MultiEdit") return false;
      if (!filePath) return false;
      const norm = filePath.replace(/[\\/]/g, "/");
      return FORBIDDEN_PATH_FRAGMENTS.some(frag => norm.includes(frag));
    },
    reasonKey: "buildArtifact",
  },
  {
    name: "copy-into-build-artifact-dir",
    matches: ({ toolName, command }) => {
      if (toolName !== "Bash") return false;
      if (!command) return false;
      const cmdLower = command.toLowerCase();
      if (!/\b(cp|copy-item|robocopy|xcopy)\b/.test(cmdLower)) return false;
      const norm = command.replace(/[\\/]/g, "/");
      return /\/?release\/.*-?unpacked/.test(norm);
    },
    reasonKey: "buildArtifact",
  },
  {
    name: "hardcoded-pid-kill",
    matches: ({ toolName, command }) => {
      if (toolName !== "Bash") return false;
      if (!command) return false;
      return /Stop-Process.*-Id\s+\d{4,5}/.test(command) ||
             /(?<![A-Za-z])\/kill\s+\d{3,}/.test(command) ||
             /\btaskkill\s+\/PID\s+\d{3,}/i.test(command);
    },
    reasonKey: "hardcodedPid",
  },
];

const DEFAULT_REDIRECTS = {
  buildArtifact: {
    headline: "Refusing to write into a build artifact directory.",
    detail:   "These paths (release/<plat>-unpacked/, app.asar.unpacked/, " +
              "app.asar) are GENERATED by the project's build tool. Manual " +
              "edits get overwritten on the next build and leave archive " +
              "metadata out of sync with actual contents (manifests ENOENT " +
              "and similar spooky-action-at-a-distance failures).",
    fix:      "Run the project's standard rebuild command instead. " +
              "If you don't know it, look at package.json scripts, the " +
              "build/ directory, or the install docs - the rebuild will " +
              "regenerate this directory cleanly.",
  },
  hardcodedPid: {
    headline: "Refusing to kill a process by hardcoded PID.",
    detail:   "PIDs change every launch (and across machines). Hardcoding " +
              "one in a script will work once, then silently fail when the " +
              "number rotates to a different process the next time it runs.",
    fix:      "Find PIDs by process name instead. Examples:\n" +
              "  PowerShell: Get-Process -Name <name> | Stop-Process -Force\n" +
              "  POSIX:      pkill -f <pattern>\n" +
              "If your project ships a stop/kill script, use that - it " +
              "should already do the name lookup.",
  },
};

function loadOverrides() {
  try {
    const p = path.join(__dirname, "anti-pattern-redirects.json");
    if (fs.existsSync(p)) {
      const parsed = JSON.parse(fs.readFileSync(p, "utf8"));
      return Object.assign({}, DEFAULT_REDIRECTS, parsed);
    }
  } catch (err) {
    process.stderr.write(
      "[anti-pattern-guard] WARNING: failed to read anti-pattern-redirects.json: " +
      err.message + " - using defaults\n"
    );
  }
  return DEFAULT_REDIRECTS;
}

function readStdin() {
  try { return fs.readFileSync(0, "utf8"); } catch { return ""; }
}

function extractToolInput(raw) {
  if (!raw) return { toolName: "", command: "", filePath: "" };
  let parsed;
  try { parsed = JSON.parse(raw); } catch { return { toolName: "", command: "", filePath: "" }; }
  const ti = parsed.tool_input || {};
  return {
    toolName: parsed.tool_name || "",
    command: ti.command || "",
    filePath: ti.file_path || ti.filePath || "",
  };
}

function deny(reason) {
  const out = {
    hookSpecificOutput: {
      hookEventName: "PreToolUse",
      permissionDecision: "deny",
      permissionDecisionReason: reason,
    },
  };
  process.stdout.write(JSON.stringify(out));
}

(function main() {
  const raw = readStdin();
  const ctx = extractToolInput(raw);
  const redirects = loadOverrides();
  for (const p of PATTERNS) {
    try {
      if (p.matches(ctx)) {
        const r = redirects[p.reasonKey] || DEFAULT_REDIRECTS[p.reasonKey];
        const reason =
          r.headline + "\n\n" +
          r.detail + "\n\n" +
          "→ Fix:\n  " + r.fix;
        deny(reason);
        process.exit(0);
      }
    } catch {
      // Never let a buggy rule take down the hook - fall through to allow.
    }
  }
  process.exit(0);
})();
